// Phase 14 fiscal handoff contracts.
//
// FastFood Riza does not perform Kosovo fiscalization. EnterNet operates the fiscal
// device and F-LINK software and remains responsible for every fiscal behaviour: ATK
// rules, signing, certificates, fiscal numbering and device protocol. This module
// describes only what this POS can prove from its own immutable records: the finalized
// sale data handed off, and the delivery state of that handoff.
//
// Nothing here is a fiscal document. No field represents a fiscal receipt number, fiscal
// signature or tax-authority identifier, because this system does not produce them.

/**
 * Delivery state of one settlement's handoff. This is operational integration state and
 * is deliberately separate from financial truth: a settlement is PAID regardless of what
 * this value says, and no transition here ever alters an order, payment or ledger row.
 */
export const FISCAL_HANDOFF_STATES = [
  'PENDING',
  'SENT',
  'CONFIRMED',
  'FAILED',
  'RETRY_REQUIRED',
] as const;
export type FiscalHandoffState = (typeof FISCAL_HANDOFF_STATES)[number];

/** One sold line, from the trigger-frozen OrderItem snapshot. */
export interface FiscalSaleLine {
  /** Stable identity of the source line in this POS, for correlation only. */
  lineId: string;
  productId: string;
  productName: string;
  sku: string;
  categoryName: string;
  quantity: number;
  /** Decimal text throughout: money never crosses this boundary as a JS number. */
  unitPrice: string;
  /** Tax rate recorded on the line at sale time, as configured in the POS. */
  taxRate: string;
  /** Whether the recorded unit price already includes tax. */
  taxMode: 'INCLUSIVE' | 'EXCLUSIVE';
  subtotal: string;
  discount: string;
  tax: string;
  total: string;
  /** Selected modifiers, whose price adjustments are already folded into the line totals. */
  modifiers: { groupName: string; name: string; priceAdjustment: string }[];
}

/** One tender recorded against the sale. */
export interface FiscalSaleTender {
  method: 'CASH' | 'CARD' | 'COMPANY_ACCOUNT';
  amount: string;
  /** External terminal reference for a card tender, where the POS recorded one. */
  transactionReference: string | null;
  /** Present only for a company-account tender; the Phase 9 ledger remains authoritative. */
  companyId: string | null;
}

/** Tax totals as already stored by this POS. No tax is recomputed for the provider. */
export interface FiscalTaxLine {
  taxRate: string;
  taxMode: 'INCLUSIVE' | 'EXCLUSIVE';
  /** Sum of line totals at this rate and mode. */
  net: string;
  tax: string;
  gross: string;
}

/**
 * The deterministic sale payload handed to the provider.
 *
 * Every field is sourced from an immutable record this POS already owns. The shape is
 * this system's own contract, not an F-LINK contract: the real provider format is
 * unknown, so the adapter is responsible for translating this into whatever EnterNet
 * specifies once that specification exists.
 */
export interface FiscalSalePayload {
  /** Schema version of this internal payload, so a later provider mapping can pin it. */
  payloadVersion: 1;
  /** Settlement identity. A settlement exists if and only if the order is PAID. */
  settlementId: string;
  orderId: string;
  orderNumber: string;
  /** Idempotent correlation key; stable for the life of this settlement. */
  correlationKey: string;
  /** Settlement time in UTC, the moment the sale became final. */
  settledAt: string;
  orderType: 'DINE_IN' | 'TAKEAWAY';
  currency: string;
  subtotal: string;
  discount: string;
  tax: string;
  total: string;
  lines: FiscalSaleLine[];
  taxBreakdown: FiscalTaxLine[];
  tenders: FiscalSaleTender[];
  /** Branch and organization identity already configured in this POS. */
  seller: {
    organizationId: string;
    organizationName: string;
    branchId: string;
    branchCode: string;
    branchName: string;
    timezone: string;
  };
  /** Operator identity recorded on the settlement. */
  cashier: { userId: string; name: string };
  /** Table and waiter snapshots, where the order carried them. */
  service: { tableName: string | null; waiterName: string | null };
}

/** Operational record of one settlement's handoff, as reported to operators. */
export interface FiscalHandoffRecord {
  id: string;
  settlementId: string;
  orderId: string;
  orderNumber: string;
  correlationKey: string;
  state: FiscalHandoffState;
  /** Provider name this handoff targets, from configuration. */
  provider: string;
  attempts: number;
  lastAttemptAt: string | null;
  confirmedAt: string | null;
  /** Provider-supplied reference, stored verbatim and never generated by this POS. */
  providerReference: string | null;
  /** Failure text from the adapter, already free of credentials. */
  lastError: string | null;
  settledAt: string;
  total: string;
  currency: string;
  createdAt: string;
  updatedAt: string;
}

export interface FiscalStatusSummary {
  /** False until an operator configures a provider; the default deployment. */
  enabled: boolean;
  provider: string | null;
  /** True when the provider transport is not yet implemented. */
  transportPending: boolean;
  counts: Record<FiscalHandoffState, number>;
  unresolved: number;
  oldestUnresolvedAt: string | null;
}

/** Compact state for one order, shown on payment and order detail. */
export interface FiscalOrderStatus {
  settlementId: string | null;
  state: FiscalHandoffState | null;
  providerReference: string | null;
  attempts: number;
  lastError: string | null;
}
