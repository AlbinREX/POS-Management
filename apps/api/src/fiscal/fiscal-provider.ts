// Fiscal provider boundary.
//
// EnterNet operates the fiscal device and F-LINK software and is responsible for every
// fiscal behaviour. This interface is the only place a provider is spoken to, so the
// rest of the system never learns a transport, a credential or a fiscal rule.
//
// The real F-LINK transport is NOT implemented, because its protocol, payload format,
// endpoint semantics, authentication and error taxonomy have not been supplied. Guessing
// any of them would produce an adapter that appears to work and silently does the wrong
// thing. Until EnterNet's specification arrives, the only adapters here are ones that
// cannot lie: a disabled adapter, and a sandbox adapter used solely by verification.
import type { FiscalSalePayload } from '@restaurant/shared-types';

/**
 * Outcome of one delivery attempt.
 *
 * `retryable` distinguishes a transient condition, such as an unreachable device, from a
 * permanent rejection that a human must resolve. Only the provider can classify this
 * correctly, so the adapter decides and the service records what it is told.
 */
export type FiscalDeliveryResult =
  | {
      status: 'confirmed';
      /** Provider-supplied reference, stored verbatim. Never generated by this POS. */
      providerReference: string | null;
    }
  | { status: 'failed'; retryable: boolean; error: string };

export interface FiscalProvider {
  /** Stable provider identifier recorded on every handoff row. */
  readonly name: string;
  /**
   * True when this adapter can actually reach a provider. A false value means handoffs
   * accumulate as PENDING and are never reported as delivered.
   */
  readonly ready: boolean;
  /**
   * Deliver one settled sale. Implementations must be idempotent with respect to
   * `payload.correlationKey`: re-delivering the same key must not produce a second
   * fiscal document at the provider.
   */
  deliver(payload: FiscalSalePayload): Promise<FiscalDeliveryResult>;
}

/**
 * The default adapter for every deployment until EnterNet supplies their specification.
 *
 * It never contacts anything and never claims success. Handoff rows remain PENDING and
 * visible to operators, which is the honest state: the sale is final in this POS and has
 * not been delivered to a fiscal provider.
 */
export class UnconfiguredFiscalProvider implements FiscalProvider {
  readonly name: string;
  readonly ready = false;
  constructor(name = 'unconfigured') {
    this.name = name;
  }
  deliver(): Promise<FiscalDeliveryResult> {
    return Promise.resolve({
      status: 'failed',
      retryable: true,
      error:
        'No fiscal provider transport is implemented. EnterNet F-LINK integration requires the provider specification.',
    });
  }
}

/**
 * Sandbox adapter for verification only.
 *
 * It exercises the confirmed, retryable-failure and permanent-failure paths and the
 * idempotency contract without pretending to be a fiscal device. Its references are
 * explicitly marked as sandbox so no test artefact can be mistaken for a fiscal number,
 * and it refuses to run outside a non-production environment.
 */
export class SandboxFiscalProvider implements FiscalProvider {
  readonly name = 'sandbox';
  readonly ready = true;
  private readonly delivered = new Map<string, string>();
  constructor(
    private readonly behaviour: 'confirm' | 'retryable' | 'permanent' = 'confirm',
    nodeEnv = process.env.NODE_ENV,
  ) {
    if (nodeEnv === 'production')
      throw new Error('The sandbox fiscal provider must never run in production');
  }
  deliver(payload: FiscalSalePayload): Promise<FiscalDeliveryResult> {
    if (this.behaviour === 'retryable')
      return Promise.resolve({
        status: 'failed',
        retryable: true,
        error: 'Sandbox provider is unreachable',
      });
    if (this.behaviour === 'permanent')
      return Promise.resolve({
        status: 'failed',
        retryable: false,
        error: 'Sandbox provider rejected the sale',
      });
    // Idempotent by correlation key: a repeat delivery returns the original reference
    // rather than issuing a second one.
    const existing = this.delivered.get(payload.correlationKey);
    if (existing) return Promise.resolve({ status: 'confirmed', providerReference: existing });
    const reference = `sandbox-${payload.correlationKey}`;
    this.delivered.set(payload.correlationKey, reference);
    return Promise.resolve({ status: 'confirmed', providerReference: reference });
  }
}

/**
 * Select the adapter from configuration. Credentials and endpoints come only from the
 * environment, never from the database, a request or the frontend.
 *
 * `enternet-flink` deliberately resolves to the unconfigured adapter: naming the
 * provider does not create a transport that does not exist.
 */
export function createFiscalProvider(env = process.env): FiscalProvider {
  const configured = (env.FISCAL_PROVIDER ?? '').trim();
  const enabled = env.FLINK_ENABLED === 'true';
  if (!configured || !enabled) return new UnconfiguredFiscalProvider(configured || 'unconfigured');
  if (configured === 'sandbox' && env.NODE_ENV !== 'production') return new SandboxFiscalProvider();
  // Any other value, including enternet-flink, has no implemented transport yet.
  return new UnconfiguredFiscalProvider(configured);
}
